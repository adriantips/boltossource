#!/usr/bin/env python3
# ===========================================================================
#  BoltOS TV  -  tv/mkaactab.py
#
#  Writes tv/aactab.c: the fixed tables AAC-LC decoding needs -- the
#  scalefactor and eleven spectral Huffman codebooks, the scalefactor band
#  edges for each sample rate, TNS's band limits and coefficient maps. They
#  are the tables of ISO/IEC 14496-3 (subpart 4, annex 4.A), and this reads
#  them out of FFmpeg's libavcodec/aactab.c (LGPL-2.1+), where they are typed
#  in already, rather than typing them in again.
#
#    python3 tv/mkaactab.py path/to/FFmpeg/libavcodec/aactab.c
# ===========================================================================
import re, sys

src = open(sys.argv[1]).read()


def array(name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit("not found: " + name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    return [t.strip() for t in body.split(",") if t.strip()]


def ints(name):
    return [int(t, 0) for t in array(name)]


def ptrs(name):
    return array(name)


out = []
w = out.append


def emit(ctype, name, vals, per=12, fmt=str):
    w("const %s %s[%d] = {" % (ctype, name, len(vals)))
    for i in range(0, len(vals), per):
        w("    " + ", ".join(fmt(v) for v in vals[i:i + per]) + ",")
    w("};")


w("/* ===========================================================================")
w(" *  BoltOS TV  -  tv/aactab.c   (generated by tv/mkaactab.py: do not edit)")
w(" *")
w(" *  The fixed tables of AAC-LC, from ISO/IEC 14496-3, as typed in by")
w(" *  FFmpeg's libavcodec/aactab.c (LGPL-2.1+).")
w(" * ===========================================================================*/")
w("#include <stdint.h>")
w('#include "aac.h"')
w("")
emit("uint32_t", "aac_sf_code", ints("ff_aac_scalefactor_code"), 8, lambda v: "0x%05x" % v)
emit("uint8_t", "aac_sf_bits", ints("ff_aac_scalefactor_bits"), 16)
w("")
sizes = []
for b in range(1, 12):
    c, l = ints("codes%d" % b), ints("bits%d" % b)
    assert len(c) == len(l)
    sizes.append(len(c))
    emit("uint16_t", "aac_cb%d_code" % b, c, 10, lambda v: "0x%04x" % v)
    emit("uint8_t", "aac_cb%d_bits" % b, l, 20)
w("const uint16_t *const aac_cb_code[11] = { %s };" % ", ".join("aac_cb%d_code" % b for b in range(1, 12)))
w("const uint8_t *const aac_cb_bits[11] = { %s };" % ", ".join("aac_cb%d_bits" % b for b in range(1, 12)))
w("const uint16_t aac_cb_size[11] = { %s };" % ", ".join(map(str, sizes)))
w("")
emit("uint8_t", "aac_num_swb_1024", ints("ff_aac_num_swb_1024"), 13)
emit("uint8_t", "aac_num_swb_128", ints("ff_aac_num_swb_128"), 13)
emit("uint8_t", "aac_tns_max_bands_1024", ints("ff_tns_max_bands_1024"), 13)
emit("uint8_t", "aac_tns_max_bands_128", ints("ff_tns_max_bands_128"), 13)
w("")
done = set()
for tab in ("ff_swb_offset_1024", "ff_swb_offset_128"):
    for p in ptrs(tab):
        if p in done:
            continue
        done.add(p)
        emit("uint16_t", "aac_" + p, ints(p), 16)
    w("const uint16_t *const aac_%s[13] = { %s };" % (tab[3:], ", ".join("aac_" + p for p in ptrs(tab))))
w("")
for p in ("tns_tmp2_map_0_3", "tns_tmp2_map_0_4", "tns_tmp2_map_1_3", "tns_tmp2_map_1_4"):
    emit("float", "aac_" + p, [float(v) for v in array(p)], 4, lambda v: "%.8ff" % v)
w("/* [2 * coef_compress + coef_res]. Negated, as FFmpeg has them: tv/aac.c flips the sign. */")
w("const float *const aac_tns_map[4] = { aac_tns_tmp2_map_0_3, aac_tns_tmp2_map_0_4, "
  "aac_tns_tmp2_map_1_3, aac_tns_tmp2_map_1_4 };")
open(sys.argv[2] if len(sys.argv) > 2 else "tv/aactab.c", "w").write("\n".join(out) + "\n")
print("tables written")
