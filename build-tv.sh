#!/usr/bin/env bash
# ===========================================================================
#  BoltOS TV build: the same boot chain as the desktop, a kernel with none of
#  the desktop in it, and the films the home screen plays.
#
#    bash build-tv.sh           -> iso/boltostv.img       raw disk, for QEMU
#                                  iso/boltos-tv.iso      bootable CD image
#                                  iso/boltostv-usb.img.gz  USB stick, BIOS + UEFI
#
#  Unlike build.sh this does not need Windows. It looks for a toolchain in, in
#  order: $BOLTOS_TOOLS, build/.tools/env/bin (see TV.md for the one-line
#  micromamba install), msys2 at /c/msys64, and finally PATH. It wants nasm,
#  clang, ld.lld, lld-link, llvm-objcopy and a Python with pycdlib.
#
#  What is in the TV kernel is a list, below, and it is short on purpose: the
#  scheduler, memory, ACPI, PCI, USB, PS/2, HDA/AC97, the e1000/virtio NICs,
#  the IPv4/IPv6 + TLS stack, the glass drawing layer, the fonts, the HTML/CSS
#  engine and the TV shell. No window manager, no shell, no compilers, no
#  filesystem, no DOOM -- only the disk drivers and FAT32, so that an update
#  from boltos.dev (kernel/sysupdate.c) can go onto the stick it started from. tv/stubs.c is where the few places the shared code
#  reaches for the desktop are answered instead.
# ===========================================================================
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

# ---- toolchain ------------------------------------------------------------
TOOLS="${BOLTOS_TOOLS:-$ROOT/build/.tools/env/bin}"
if [ -x "$TOOLS/nasm" ] && [ -x "$TOOLS/ld.lld" ]; then
    export PATH="$TOOLS:$PATH"
elif [ -d /c/msys64 ] || [ -d /mnt/c/msys64 ]; then
    M=/c/msys64; [ -d "$M" ] || M=/mnt/c/msys64
    export PATH="$M/ucrt64/bin:$M/usr/bin:$PATH"
fi
need() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: $1 not found (see TV.md, 'Building it')"; exit 1; }; }
pick() { for c in "$@"; do command -v "$c" >/dev/null 2>&1 && { echo "$c"; return; }; done; echo "$1"; }
NASM=$(pick nasm nasm.exe)
CLANG=$(pick clang clang.exe)
LLD=$(pick ld.lld ld.lld.exe)
LLDLINK=$(pick lld-link lld-link.exe)
OBJCOPY=$(pick llvm-objcopy objcopy objcopy.exe)
for t in "$NASM" "$CLANG" "$LLD" "$LLDLINK" "$OBJCOPY"; do need "$t"; done

PYTHON="${BOLTOS_PYTHON-}"
if [ -z "$PYTHON" ]; then
    for c in "$TOOLS/python3" python3 python; do
        command -v "$c" >/dev/null 2>&1 || [ -x "$c" ] || continue
        if "$c" -c "import pycdlib" >/dev/null 2>&1; then PYTHON="$c"; break; fi
        [ -n "$PYTHON" ] || PYTHON="$c"
    done
fi
[ -n "$PYTHON" ] || { echo "ERROR: no host Python found (set BOLTOS_PYTHON)"; exit 1; }

fsize() { wc -c < "$1" | tr -d ' '; }

B=build/tv
mkdir -p "$B" iso

BOLT_BUILD_ID="$(date '+%Y-%m-%d %H:%M')"
if command -v git >/dev/null 2>&1 && git rev-parse --short HEAD >/dev/null 2>&1; then
    BOLT_BUILD_ID="$BOLT_BUILD_ID $(git rev-parse --short HEAD)"
    git diff --quiet 2>/dev/null || BOLT_BUILD_ID="$BOLT_BUILD_ID+dirty"
fi
mkdir -p "$B/gen"
# tv/VERSION: release.sh raises it and publishes the kernel as an update.
BOLT_VERSION="$(tr -d ' \n' < tv/VERSION)"
cat > "$B/gen/buildid.h" <<EOF
#pragma once
/* Generated by build-tv.sh on every build. Do not edit. */
#define BOLT_BUILD_ID "$BOLT_BUILD_ID"
#define BOLT_VERSION "$BOLT_VERSION"
EOF
echo "      BoltOS TV $BOLT_VERSION, build id: $BOLT_BUILD_ID"

# Embed a file as an ELF object exposing _binary_<name>_start/_end. Run from
# the output directory so the symbol is named after the bare file name.
embed() {   # embed SRC NAME  -> $B/NAME.o
    cp "$1" "$B/$2"
    ( cd "$B" && "$OBJCOPY" -I binary -O elf64-x86-64 "$2" "${2//[-.]/_}.o" )
    KOBJS+=("$B/${2//[-.]/_}.o")
}

echo "[1/6] boot chain (stage1 + stage2 + BOOTX64.EFI), TV variant"
"$NASM" -f bin boot/stage1.asm -o "$B/stage1.bin"
"$NASM" -f bin -DBOLT_TV boot/stage2.asm -o "$B/stage2.bin"
S2SIZE=$(fsize "$B/stage2.bin")
[ "$S2SIZE" -le $((32 * 512)) ] || { echo "ERROR: stage2 is $S2SIZE bytes, over 32 sectors"; exit 1; }
"$CLANG" --target=x86_64-unknown-windows -ffreestanding -fno-stack-protector \
         -fshort-wchar -mno-red-zone -mno-sse -mno-sse2 -mno-mmx -mno-80387 \
         -Wall -O2 -Iinclude -DBOLT_TV -c boot/uefi_boot.c -o "$B/uefi_boot.o"
"$LLDLINK" -subsystem:efi_application -entry:efi_main -out:"$B/BOOTX64.EFI" "$B/uefi_boot.o"

echo "[2/6] kernel asm"
KOBJS=()
"$NASM" -f elf64 kernel/boot.asm    -o "$B/kboot.o"
"$NASM" -f elf64 kernel/isr.asm     -o "$B/isr.o"
"$CLANG" --target=x86_64-elf -mcmodel=kernel -c libc/setjmp.S -o "$B/setjmp.o"
KOBJS+=("$B/kboot.o" "$B/isr.o" "$B/setjmp.o")

echo "[3/6] kernel C"
CFLAGS=(--target=x86_64-elf -ffreestanding -fno-pic -fno-pie
        -mcmodel=kernel -mno-red-zone -msse -msse2 -mno-mmx -mno-80387
        -fstack-protector-strong -mstack-protector-guard=global
        -Wall -Wextra -O2 -std=c11 -DBOLT_TV -I"$B/gen" -Itv -Iinclude -Ivendor/pl_mpeg -c)
# Which of boltos.dev's update descriptions it asks for: release.sh --channel
# NAME builds one that asks for a test channel.
[ -n "${BOLTOS_UPDATE_CHANNEL:-}" ] && CFLAGS+=("-DUPDATE_CHANNEL=\"$BOLTOS_UPDATE_CHANNEL\"")
LIBC_SRCS=(libc/string.c libc/string_ext.c libc/malloc.c libc/printf.c
           libc/stdlib.c libc/support.c libc/math.c libc/time.c)
SRCS=(
    # the machine
    kernel/serial.c kernel/kprintf.c kernel/gdt.c kernel/idt.c kernel/interrupts.c
    kernel/pic.c kernel/pit.c kernel/acpi.c kernel/apic.c kernel/hpet.c kernel/timeout.c
    kernel/pci.c kernel/hw.c kernel/sched.c kernel/stackguard.c
    kernel/font8x8.c kernel/font_latin1.c
    mm/pmm.c mm/vmm.c mm/kheap.c mm/dma.c
    # input, picture, sound
    drivers/keyboard.c kernel/keymap.c kernel/kbdlayout.c drivers/mouse.c drivers/xhci.c
    drivers/framebuffer.c
    drivers/audio.c drivers/hda.c drivers/ac97.c drivers/pcspk.c kernel/mixer.c
    # network
    net/driver.c drivers/e1000.c drivers/virtio_net.c
    net/netif.c net/eth.c net/arp.c net/ip.c net/icmp.c net/udp.c net/tcp.c
    net/ip6.c net/icmp6.c net/nd6.c net/netaddr.c net/firewall.c
    net/dns.c net/dhcp.c net/ntp.c net/http.c net/inflate.c
    net/tls.c net/crypto.c net/p256.c net/p384.c net/rsa.c net/x509.c
    # the disk it started from, for updates
    kernel/blk.c drivers/ata.c drivers/ahci.c drivers/nvme.c drivers/usbstor.c fs/fat32.c kernel/sysupdate.c
    # drawing and the web engine
    kernel/gfx.c kernel/font.c kernel/image.c
    kernel/html.c kernel/dom.c
    # the television
    tv/main.c tv/stubs.c tv/video.c tv/art.c tv/ui.c tv/shell.c tv/home.c
    tv/live.c tv/inputs.c tv/web.c tv/adblock.c tv/settings.c tv/netsvc.c tv/sfx.c
)
mkdir -p "$B/obj"
compile() {   # compile SRC [extra flags...]
    local c="$1"; shift
    local o="$B/obj/$(echo "${c%.c}" | tr '/' '_').o"
    "$CLANG" "${CFLAGS[@]}" "$@" "$c" -o "$o"
    echo "$o"
}
# Compile in parallel: there are ninety files and nothing orders them.
JOBS=$( (sysctl -n hw.ncpu || nproc || echo 4) 2>/dev/null | head -1)

PIDS=(); OUTS=()
run_bg() { "$@" > /dev/null & PIDS+=($!); }
for c in "${LIBC_SRCS[@]}"; do
    run_bg compile "$c" -fno-math-errno -fno-trapping-math
    OUTS+=("$B/obj/$(echo "${c%.c}" | tr '/' '_').o")
    while [ "$(jobs -rp | wc -l)" -ge "$JOBS" ]; do sleep 0.05; done
done
for c in "${SRCS[@]}"; do
    run_bg compile "$c"
    OUTS+=("$B/obj/$(echo "${c%.c}" | tr '/' '_').o")
    while [ "$(jobs -rp | wc -l)" -ge "$JOBS" ]; do sleep 0.05; done
done
FAIL=0
for p in "${PIDS[@]}"; do wait "$p" || FAIL=1; done
[ "$FAIL" = 0 ] || { echo "ERROR: a kernel source failed to compile (above)"; exit 1; }
KOBJS+=("${OUTS[@]}")

echo "[4/6] assets: fonts, art, films"
UIFONTS=(
    "font_r:assets/fonts/Inter.ttf:wght=400:opsz=14"
    "font_m:assets/fonts/Inter.ttf:wght=500:opsz=14"
    "font_sb:assets/fonts/Inter.ttf:wght=600:opsz=14"
    "font_b:assets/fonts/Inter.ttf:wght=700:opsz=14"
    "font_d:assets/fonts/Inter.ttf:wght=300:opsz=32"
    "font_mono:assets/fonts/DejaVuSansMono.ttf"
    "font_monob:assets/fonts/DejaVuSansMono-Bold.ttf"
)
for spec in "${UIFONTS[@]}"; do
    IFS=: read -r fname fsrc fa fb <<< "$spec"
    if [ ! -f "$B/$fname.bfnt" ] || [ "$fsrc" -nt "$B/$fname.bfnt" ] || [ mkuifont.py -nt "$B/$fname.bfnt" ]; then
        "$PYTHON" mkuifont.py "$fsrc" "$B/$fname.bfnt.tmp" $fa $fb > /dev/null
        mv "$B/$fname.bfnt.tmp" "$B/$fname.bfnt"
    fi
    ( cd "$B" && "$OBJCOPY" -I binary -O elf64-x86-64 "$fname.bfnt" "${fname}_bfnt.o" )
    KOBJS+=("$B/${fname}_bfnt.o")
done
# App tiles and UI glyphs, drawn by tv/mkart.py and committed.
for a in tv/art/*.png; do
    [ -e "$a" ] || { echo "ERROR: tv/art is empty -- run: python tv/mkart.py"; exit 1; }
    embed "$a" "art-$(basename "$a")"
done
# The films and their guide stills, cut by tv/mkmedia.py and committed.
FILMS=(lofoten lagoon sunset aurora kauai autumn)
for f in "${FILMS[@]}"; do
    [ -f "tv/media/$f.m1v" ] || { echo "ERROR: tv/media/$f.m1v missing -- see tv/mkmedia.py"; exit 1; }
    embed "tv/media/$f.m1v" "film-$f.m1v"
    embed "tv/media/$f.jpg" "film-$f.jpg"
done

echo "[5/6] link"
printf '%s\n' "${KOBJS[@]}" > "$B/kobjs.rsp"
"$LLD" -m elf_x86_64 -T linker.ld --oformat binary -o "$B/kernel.bin" @"$B/kobjs.rsp"
"$LLD" -m elf_x86_64 -T linker.ld -o "$B/kernel.elf" @"$B/kobjs.rsp" 2>/dev/null || true
KSIZE=$(fsize "$B/kernel.bin")
KSECT=$(( (KSIZE + 511) / 512 ))
echo "      kernel.bin = $KSIZE bytes ($((KSIZE / 1048576)) MiB) -> $KSECT sectors"

echo "[6/6] images"
IMG=iso/boltostv.img
dd if=/dev/zero          of="$IMG" bs=512 count=$((34 + KSECT)) 2>/dev/null
dd if="$B/stage1.bin"    of="$IMG" bs=512 seek=0  conv=notrunc 2>/dev/null
dd if="$B/stage2.bin"    of="$IMG" bs=512 seek=1  conv=notrunc 2>/dev/null
dd if="$B/kernel.bin"    of="$IMG" bs=512 seek=34 conv=notrunc 2>/dev/null
"$PYTHON" mkboothdr.py "$IMG" 34 "$KSIZE"
echo "OK -> $IMG ($(fsize "$IMG") bytes)"

mkdir -p "$B/esp/EFI/BOOT"
cp "$B/BOOTX64.EFI" "$B/esp/EFI/BOOT/BOOTX64.EFI"
cp "$B/kernel.bin"  "$B/esp/kernel.bin"
echo "OK -> $B/esp/ (UEFI: BOOTX64.EFI + kernel.bin)"

if "$PYTHON" -c "import pycdlib" >/dev/null 2>&1; then
    "$PYTHON" mkhpfs.py "$IMG" iso/boltos-tv.iso "BoltOS TV" > /dev/null
    echo "OK -> iso/boltos-tv.iso ($(fsize iso/boltos-tv.iso) bytes)"
else
    echo "WARN: $PYTHON has no pycdlib; skipping the ISO ($PYTHON -m pip install pycdlib)"
fi

# One copy of the kernel on the stick, not two: stage2 is pointed at the
# clusters of the ESP's kernel.bin (mkusb.py --shared-kernel), so the BIOS
# path and the UEFI path read the very same bytes. With the films aboard a
# second copy would be most of a hundred megabytes of nothing new.
# The ESP has room for two, though: an update writes the new kernel beside the
# old one before it switches over (kernel/sysupdate.c). Unused, it's zeros,
# which the .gz doesn't notice.
USBIMG=iso/boltostv-usb.img
"$PYTHON" mkusb.py "$USBIMG" "$B/stage1.bin" "$B/stage2.bin" "$B/kernel.bin" "$B/BOOTX64.EFI" \
    --shared-kernel --data-mb 1 --esp-mb $(( KSIZE * 3 / 1048576 + 64 )) > /dev/null
gzip -9 -n -c "$USBIMG" > "$USBIMG.gz"
echo "OK -> $USBIMG.gz ($(fsize "$USBIMG.gz") bytes)"
