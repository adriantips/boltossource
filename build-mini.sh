#!/usr/bin/env bash
# ===========================================================================
#  BoltOS Mini build: an AArch64 kernel for the Orange Pi Zero3 (and QEMU).
#
#    bash build-mini.sh          -> build/mini/boltos.bin     the kernel (arm64 Image)
#                                   build/mini/sdcard.img     a whole microSD card
#    bash build-mini.sh run      -> build, then boot it in QEMU on this Mac
#    bash build-mini.sh pi       -> build, then send it to the Pi over USB-C
#                                   (RAM only; `pi.py install` makes it stick)
#    bash build-mini.sh release  -> build/mini-release/: the standalone Pi, with
#                                   nothing for a Mac -- no USB-C network link,
#                                   no screen sharing, no web page or dev
#                                   endpoints. The development build keeps them.
#
#  The toolchain is the one build-tv.sh uses -- clang and ld.lld from
#  build/.tools/env (see TV.md) -- because clang targets AArch64 out of the
#  box. U-Boot is prebuilt in mini/firmware (mini/firmware/build-uboot.sh
#  makes it again).
#
#  What is in the kernel is the list below: Mini's own machine layer and
#  drivers, and from the shared tree only the portable parts -- libc, the
#  heap, the glass drawing layer and the fonts.
# ===========================================================================
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

TOOLS="${BOLTOS_TOOLS:-$ROOT/build/.tools/env/bin}"
[ -x "$TOOLS/ld.lld" ] && export PATH="$TOOLS:$PATH"
need() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: $1 not found (see MINI.md, 'Building it')"; exit 1; }; }
for t in clang ld.lld llvm-objcopy; do need "$t"; done
PYTHON="${BOLTOS_PYTHON:-$TOOLS/python3}"
[ -x "$PYTHON" ] || PYTHON=python3

RELEASE=0
[ "${1:-}" = release ] && RELEASE=1
B=build/mini
[ "$RELEASE" = 1 ] && B=build/mini-release
mkdir -p "$B/obj" "$B/gen"

BOLT_BUILD_ID="$(date '+%Y-%m-%d %H:%M')"
if git rev-parse --short HEAD >/dev/null 2>&1; then
    BOLT_BUILD_ID="$BOLT_BUILD_ID $(git rev-parse --short HEAD)"
    git diff --quiet 2>/dev/null || BOLT_BUILD_ID="$BOLT_BUILD_ID+dirty"
fi
cat > "$B/gen/buildid.h" <<EOF
#pragma once
/* Generated by build-mini.sh on every build. Do not edit. */
#define BOLT_BUILD_ID "$BOLT_BUILD_ID"
EOF
[ "$RELEASE" = 1 ] && BOLT_BUILD_ID="$BOLT_BUILD_ID release"
echo "      build id: $BOLT_BUILD_ID"

CFLAGS=(--target=aarch64-none-elf -mcpu=cortex-a53 -ffreestanding -fno-pic -fno-pie
        -fno-stack-protector -fno-builtin-printf -Wall -Wextra -O2 -std=c11 -DBOLT_MINI
        -Imini -Imini/include -I"$B/gen" -Iinclude -c)
[ "$RELEASE" = 1 ] && CFLAGS+=(-DMINI_RELEASE)

LIBC_SRCS=(libc/string.c libc/string_ext.c libc/malloc.c libc/printf.c
           libc/stdlib.c libc/support.c libc/math.c libc/scanf.c)
SRCS=(
    # shared with the desktop and the TV
    mm/kheap.c kernel/gfx.c kernel/font.c kernel/font8x8.c kernel/font_latin1.c
    # the machine
    mini/main.c mini/board.c mini/fdt.c mini/klog.c mini/stubs.c mini/screen.c
    mini/input.c mini/qemu.c
)
# The web: the desktop's HTTP, TLS 1.2/1.3 and certificate code, and its page
# engine (HTML, DOM, CSS layout, JS, images), on mini/netcompat.c.
SRCS+=(net/http.c net/tls.c net/crypto.c net/wpa.c net/x509.c net/rsa.c net/p256.c net/p384.c
       net/inflate.c kernel/html.c kernel/dom.c kernel/layout.c kernel/js.c kernel/image.c
       mini/netcompat.c mini/webutil.c mini/flow.c mini/app_browser.c mini/player.c
       mini/mp4.c mini/h264.c mini/h264mb.c mini/h264pred.c mini/h264dbk.c mini/h264tab.c)
# Optional parts: compiled when present, so the kernel grows a file at a time.
for f in mini/sdio.c mini/wcn.c mini/wifi.c mini/bt.c mini/hid.c mini/emac.c mini/inet.c mini/net.c mini/netsvc.c mini/vnc.c mini/virtio.c mini/musb.c mini/usbdev.c \
         mini/ohci.c mini/usbhost.c mini/shell.c mini/ui.c \
         mini/app_terminal.c mini/app_monitor.c mini/app_notes.c mini/app_clock.c \
         mini/app_settings.c mini/app_packages.c mini/sdcard.c mini/store.c mini/dl.c \
         mini/pkg.c mini/exports.c mini/fs.c mini/rt.c mini/gc.c mini/numfmt.c mini/mathx.c mini/app_code.c \
         mini/py_obj.c mini/py_parse.c mini/py_eval.c mini/py_lib.c mini/cc.c mini/cc_eval.c mini/cc_lib.c; do
    [ -f "$f" ] || continue
    # The release build is the Pi on its own: what only a Mac uses stays out.
    if [ "$RELEASE" = 1 ]; then case "$f" in mini/musb.c|mini/vnc.c|mini/netsvc.c) continue ;; esac; fi
    SRCS+=("$f")
done

echo "[1/5] kernel"
OBJS=()
clang "${CFLAGS[@]}" -mstrict-align mini/arch/cpu.c -o "$B/obj/cpu.o"
clang --target=aarch64-none-elf -mcpu=cortex-a53 -c mini/arch/start.S -o "$B/obj/start.o"
OBJS+=("$B/obj/start.o" "$B/obj/cpu.o")

JOBS=$( (sysctl -n hw.ncpu || nproc || echo 4) 2>/dev/null | head -1)
PIDS=()
compile() {
    local c="$1"; shift
    clang "${CFLAGS[@]}" "$@" "$c" -o "$B/obj/$(echo "${c%.c}" | tr '/' '_').o"
}
for c in "${LIBC_SRCS[@]}"; do
    compile "$c" -fno-math-errno -fno-trapping-math & PIDS+=($!)
    OBJS+=("$B/obj/$(echo "${c%.c}" | tr '/' '_').o")
    while [ "$(jobs -rp | wc -l)" -ge "$JOBS" ]; do sleep 0.05; done
done
for c in "${SRCS[@]}"; do
    compile "$c" & PIDS+=($!)
    OBJS+=("$B/obj/$(echo "${c%.c}" | tr '/' '_').o")
    while [ "$(jobs -rp | wc -l)" -ge "$JOBS" ]; do sleep 0.05; done
done
FAIL=0
for p in "${PIDS[@]}"; do wait "$p" || FAIL=1; done
[ "$FAIL" = 0 ] || { echo "ERROR: a kernel source failed to compile (above)"; exit 1; }

echo "[2/5] fonts"
UIFONTS=(
    "font_r:assets/fonts/Inter.ttf:wght=400:opsz=14"
    "font_m:assets/fonts/Inter.ttf:wght=500:opsz=14"
    "font_sb:assets/fonts/Inter.ttf:wght=600:opsz=14"
    "font_b:assets/fonts/Inter.ttf:wght=700:opsz=14"
    "font_d:assets/fonts/Inter.ttf:wght=300:opsz=32"
    "font_mono:assets/fonts/DejaVuSansMono.ttf"
    "font_monob:assets/fonts/DejaVuSansMono-Bold.ttf"
)
for spec in "${UIFONTS[@]}"; do
    IFS=: read -r fname fsrc fa fb <<< "$spec"
    if [ ! -f "$B/$fname.bfnt" ] || [ "$fsrc" -nt "$B/$fname.bfnt" ] || [ mkuifont.py -nt "$B/$fname.bfnt" ]; then
        "$PYTHON" mkuifont.py "$fsrc" "$B/$fname.bfnt.tmp" $fa $fb > /dev/null
        mv "$B/$fname.bfnt.tmp" "$B/$fname.bfnt"
    fi
    ( cd "$B" && llvm-objcopy -I binary -O elf64-littleaarch64 "$fname.bfnt" "${fname}_bfnt.o" )
    OBJS+=("$B/${fname}_bfnt.o")
done

# The Wi-Fi/Bluetooth module's firmware (mini/wcn.c): Unisoc's UWE5622 runs its own
# Cortex-M code, which the Pi loads into it at every start. It's not ours to put in
# the tree, so it comes from Orange Pi's firmware repository at a fixed commit, is
# checked against these hashes, and goes into the kernel the way the fonts do.
# Without it (offline, say) the kernel builds with no Wi-Fi or Bluetooth.
FW_COMMIT=dc163b0ed2e0272d9ee31977a0e0a04884f0ae61
FW_DIR=build/mini-fw/uwe5622
FW_FILES=(
    "wcnmodem.bin:119b87ce30875734a67462f7293fb8fe85acf3270fe8b78c978ae24be7715a80"
    "wifi_2355b001_1ant.ini:1f3c40ec245a8d0b99ad1c23706597d6dd5008ab80cefb7bcc1956efc4e938f7"
    "bt_configure_pskey.ini:5a7a1f63fd68916201031d4b24a11dc67ae45f6cd695950bc325fb6a487ad0ac"
    "bt_configure_rf.ini:4044252baefdfa0e884b61d4c42f4d07f74a8f3121ba1923e782968d013d617d"
)
mkdir -p "$FW_DIR"
FW_OK=1
# BOLTOS_NO_FW=1 leaves it out on purpose: the card image published on
# boltos.dev is built that way, so it doesn't hand out Unisoc's firmware.
[ "${BOLTOS_NO_FW:-0}" = 1 ] && FW_FILES=() && FW_OK=0
for spec in ${FW_FILES[@]+"${FW_FILES[@]}"}; do
    f="${spec%%:*}"; want="${spec#*:}"
    if [ ! -f "$FW_DIR/$f" ]; then
        curl -fsSL --max-time 60 -o "$FW_DIR/$f.tmp" \
            "https://raw.githubusercontent.com/orangepi-xunlong/firmware/$FW_COMMIT/$f" 2>/dev/null \
            && mv "$FW_DIR/$f.tmp" "$FW_DIR/$f" || rm -f "$FW_DIR/$f.tmp"
    fi
    got=$(shasum -a 256 "$FW_DIR/$f" 2>/dev/null | cut -d' ' -f1 || true)
    if [ "$got" != "$want" ]; then FW_OK=0; rm -f "$FW_DIR/$f"; fi
done
if [ "$FW_OK" = 1 ]; then
    # The Wi-Fi calibration .ini, as the binary struct the firmware takes.
    "$PYTHON" mini/tools/mkwifiini.py "$FW_DIR/wifi_2355b001_1ant.ini" "$FW_DIR/wifi_ini.bin"
    # ...and the Bluetooth settings, as the payloads of two vendor HCI commands.
    "$PYTHON" mini/tools/mkbtcfg.py "$FW_DIR/bt_configure_pskey.ini" "$FW_DIR/bt_configure_rf.ini" \
        "$FW_DIR/bt_pskey.bin" "$FW_DIR/bt_rf.bin"
    for f in wcnmodem.bin wifi_ini.bin bt_pskey.bin bt_rf.bin; do
        o="$(echo "$f" | tr '.-' '__')"
        ( cd "$FW_DIR" && llvm-objcopy -I binary -O elf64-littleaarch64 "$f" "$o.o" )
        OBJS+=("$FW_DIR/$o.o")
    done
    echo "      Wi-Fi/Bluetooth firmware: UWE5622, $(( $(wc -c < "$FW_DIR/wcnmodem.bin") / 1024 )) KiB"
else
    if [ "${BOLTOS_NO_FW:-0}" = 1 ]; then echo "      Wi-Fi/Bluetooth firmware: left out (BOLTOS_NO_FW=1)"
    else echo "      Wi-Fi/Bluetooth firmware: not available (offline?): building without it"; fi
    # Every file's start and end at one address: zero bytes, so wcn.c sees none.
    clang "${CFLAGS[@]}" -x c - -o "$B/obj/nofw.o" <<'NOFW'
#define EMPTY(n) __asm__(".globl _binary_" n "_start\n.globl _binary_" n "_end\n_binary_" n "_start:\n_binary_" n "_end:\n");
EMPTY("wcnmodem_bin") EMPTY("wifi_ini_bin") EMPTY("bt_pskey_bin") EMPTY("bt_rf_bin")
NOFW
    OBJS+=("$B/obj/nofw.o")
fi

echo "[3/5] link"
ld.lld -T mini/linker.ld -o "$B/boltos.elf" "${OBJS[@]}"
llvm-objcopy -O binary "$B/boltos.elf" "$B/boltos.bin"
# Image and .bss must end below the heap at 0x41000000 (mini/mini.h).
END=$(llvm-nm "$B/boltos.elf" | awk '$3 == "__image_end" {print $1}')
[ $((16#$END)) -lt $((16#41000000)) ] || { echo "ERROR: the kernel ends at 0x$END, into the heap at 0x41000000"; exit 1; }
KSIZE=$(wc -c < "$B/boltos.bin" | tr -d ' ')
echo "      boltos.bin = $KSIZE bytes ($((KSIZE / 1024)) KiB)"

echo "[4/5] packages"
# Apps that aren't in the kernel (mini/pkg.h): each mini/pkg/<name>/ with a
# pkg.conf is compiled position-independent, linked as a shared object at 0,
# and turned into a .bpk by mkpkg.py, which refuses one that needs a kernel
# symbol exports.c doesn't have. Packages ships them; the Pi loads them.
PKG_CFLAGS=(--target=aarch64-none-elf -mcpu=cortex-a53 -ffreestanding -fpic -fno-plt -fno-stack-protector
            -fno-builtin-printf -Wall -Wextra -O2 -std=c11 -DBOLT_MINI -DBOLT_PKG
            -Imini -Imini/include -I"$B/gen" -Iinclude -c)
mkdir -p "$B/pkg"
for conf in mini/pkg/*/pkg.conf; do
    [ -f "$conf" ] || continue
    dir="$(dirname "$conf")"
    pid="$(sed -n 's/^id=//p' "$conf")"; pname="$(sed -n 's/^name=//p' "$conf")"; pver="$(sed -n 's/^version=//p' "$conf")"
    POBJS=()
    for c in "$dir"/*.c; do
        o="$B/pkg/${pid}_$(basename "${c%.c}").o"
        clang "${PKG_CFLAGS[@]}" "$c" -o "$o" || { echo "ERROR: $c failed to compile"; exit 1; }
        POBJS+=("$o")
    done
    ld.lld -shared -z now -z max-page-size=4096 -Bsymbolic --hash-style=sysv -e pkg_main -o "$B/pkg/$pid.so" "${POBJS[@]}"
    "$PYTHON" mini/tools/mkpkg.py "$B/pkg/$pid.so" "$B/pkg/$pid-$pver.bpk" --id "$pid" --name "$pname" \
        --version "$pver" --exports mini/exports.c
done

"$PYTHON" mini/tools/pkgindex.py "$B/pkg/index.json" "$B/pkg" mini/pkg

echo "[5/5] microSD image"
"$PYTHON" mini/tools/mkcard.py "$B/sdcard.img" --uboot mini/firmware/u-boot-sunxi-with-spl.bin \
    --kernel "$B/boltos.bin"

case "${1:-}" in
run)
    shift
    exec bash mini/tools/run-qemu.sh "$@" ;;
pi)
    shift
    exec "$PYTHON" mini/tools/pi.py boot "$B/boltos.bin" "$@" ;;
esac
