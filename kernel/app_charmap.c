/* ===========================================================================
 *  BoltOS  -  kernel/app_charmap.c
 *  Character Map. The grid of every glyph the font actually has, so that
 *  finding a degree sign is a thing you can do without knowing it is 0xB0.
 *
 *  BoltOS draws text from two baked-in faces (the 8x8 retro one and the 8x16
 *  Arial one) and they do NOT cover the same code points -- the retro face
 *  stops caring somewhere in the high half. That is the reason this exists in
 *  the shape it does: the grid greys out what the *current* face cannot draw,
 *  so a character you pick here is a character that will appear when you paste
 *  it. Switching the face re-greys the grid in front of you.
 *
 *  Picking builds a little string at the bottom rather than copying one
 *  character at a time, because nobody ever wants exactly one -- they want
 *  "±3 °C" and would otherwise paste four times.
 * ===========================================================================*/
#include <stdint.h>
#include <stdio.h>
#include "gui.h"
#include "font.h"
#include "clipboard.h"
#include "keyboard.h"
#include "notify.h"
#include "string.h"

#define FIRST_CH  0x20
#define LAST_CH   0xFF
#define NCH       (LAST_CH - FIRST_CH + 1)
#define COLS      16
#define HEAD_H    44
#define FOOT_H    82
#define PICK_CAP  96

static struct {
    int  sel;                  /* 0..NCH-1 */
    int  face;                 /* FONT_RETRO / FONT_ARIAL */
    char pick[PICK_CAP];
    int  npick;
    int  cw, ch;               /* last client size, for hit-testing */
    int  cell;                 /* cell size from the last draw, for hit-testing.
                                * The grid ORIGIN deliberately does not live here:
                                * the draw works in absolute coordinates and clicks
                                * arrive client-local, so a stored origin is a
                                * hit-test bug waiting to be written. The centring
                                * margin is the same in both frames. */
} C;

/* Names for the ones whose shape does not tell you what they are. Everything
 * else is its own label. */
static const char *char_note(int c) {
    switch (c) {
    case 0x20: return "space";
    case 0xA0: return "no-break space";
    case 0xA1: return "inverted exclamation";
    case 0xA3: return "pound sign";
    case 0xA9: return "copyright sign";
    case 0xAB: return "left guillemet";
    case 0xAE: return "registered sign";
    case 0xB0: return "degree sign";
    case 0xB1: return "plus-minus sign";
    case 0xB5: return "micro sign";
    case 0xB6: return "pilcrow";
    case 0xB7: return "middle dot";
    case 0xBB: return "right guillemet";
    case 0xBF: return "inverted question mark";
    case 0xD7: return "multiplication sign";
    case 0xDF: return "sharp s";
    case 0xF7: return "division sign";
    default:   return 0;
    }
}

/* Is there a glyph here in the face currently selected? Asked of the renderer
 * rather than tabulated, because the faces get regenerated by mkfont.py and a
 * table here would quietly go stale. Spaces are the exception: they are
 * legitimately blank, and greying them out would be a lie. */
static int glyph_present(int c) {
    if (c == 0x20 || c == 0xA0) return 1;
    int saved = g_get_font();
    g_set_font(C.face);
    int ink = g_glyph_ink((char)c);
    g_set_font(saved);
    return ink;
}

static void pick_append(int c) {
    if (C.npick >= PICK_CAP - 1) return;
    C.pick[C.npick++] = (char)c;
    C.pick[C.npick] = 0;
}

static void do_copy(void) {
    if (!C.npick) return;
    clip_set(C.pick, C.npick);
    char msg[64];
    snprintf(msg, sizeof msg, "%d character%s copied", C.npick, C.npick == 1 ? "" : "s");
    gui_notify(NOTE_SUCCESS, "Character Map", msg);
}

/* ------------------------------------------------------------- drawing ---- */
static void btn(int x, int y, int w, int h, const char *label, uint32_t bg, uint32_t fg) {
    g_round(x, y, w, h, 7, bg, 255);
    /* centred on the caps, not on an 8 px glyph box this was written for */
    text_c(x + w / 2, y + h / 2, label, FONT_MEDIUM, 12, fg);
}

static void cm_draw(window_t *w, int cx, int cy, int cw, int ch) {
    (void)w;
    C.cw = cw; C.ch = ch;
    g_fill(cx, cy, cw, ch, COL_PANEL);

    int saved = g_get_font();

    /* --- face selector -------------------------------------------------- */
    g_text(cx + 14, cy + 15, "Font", COL_TEXT_DIM, 1);
    const char *fname[2] = { "Retro 8x8", "Arial 8x16" };
    for (int f = 0; f < 2; f++) {
        int bx = cx + 52 + f * 96, by = cy + 8;
        int on = (C.face == f);
        g_round(bx, by, 90, 24, 6, on ? COL_ACCENT : COL_PANEL_3, 255);
        g_text(bx + (90 - g_text_width(fname[f], 1)) / 2, by + 8, fname[f],
               on ? 0xFFFFFF : COL_TEXT, 1);
    }
    g_hline(cx + 10, cy + HEAD_H - 8, cw - 20, COL_PANEL_3);

    /* --- the grid -------------------------------------------------------- */
    int gw = cw - 28;
    int cell = gw / COLS;
    if (cell < 14) cell = 14;
    int rows = (NCH + COLS - 1) / COLS;
    int avail = ch - HEAD_H - FOOT_H;
    if (cell * rows > avail && rows) {
        int fit = avail / rows;
        if (fit >= 12) cell = fit;
    }
    C.cell = cell;
    int ox = cx + (cw - cell * COLS) / 2, oy = cy + HEAD_H;

    g_set_clip(cx, oy, cw, avail > 0 ? avail : 1);
    for (int i = 0; i < NCH; i++) {
        int c  = FIRST_CH + i;
        int gx = ox + (i % COLS) * cell;
        int gy = oy + (i / COLS) * cell;
        int here = glyph_present(c);

        if (i == C.sel) g_round(gx + 1, gy + 1, cell - 2, cell - 2, 4, COL_ACCENT, 255);
        else if (here)  g_round(gx + 1, gy + 1, cell - 2, cell - 2, 4, COL_PANEL_2, 255);

        if (!here) {
            /* an empty slot reads as a hole, not as a space */
            g_fill(gx + cell / 2 - 3, gy + cell / 2, 6, 1, COL_PANEL_3);
            continue;
        }
        g_set_font(C.face);
        int gh = g_font_height(1);
        g_char(gx + (cell - 8) / 2, gy + (cell - gh) / 2, (char)c,
               i == C.sel ? 0xFFFFFF : COL_TEXT, 1);
        g_set_font(saved);
    }
    g_clear_clip();

    /* --- the footer: preview, the string being built, the buttons -------- */
    int fy = cy + ch - FOOT_H;
    g_hline(cx + 10, fy, cw - 20, COL_PANEL_3);

    int sc = FIRST_CH + C.sel;
    g_round(cx + 14, fy + 10, 52, 52, 8, COL_PANEL_2, 255);
    if (glyph_present(sc)) {
        g_set_font(C.face);
        /* Arial is 16 rows tall, so scale 4 is 64px and does not fit the 52px
         * swatch -- it drew half a glyph off the top. Pick the largest scale
         * that fits the face actually selected. */
        int s = 4;
        while (s > 1 && g_font_height(s) > 48) s--;
        int gh = g_font_height(s);
        g_char(cx + 14 + (52 - 8 * s) / 2, fy + 10 + (52 - gh) / 2, (char)sc, COL_ACCENT, s);
        g_set_font(saved);
    } else {
        g_text(cx + 14 + 18, fy + 10 + 22, "-", COL_TEXT_DIM, 1);
    }

    char info[80];
    const char *note = char_note(sc);
    snprintf(info, sizeof info, "U+%04X   decimal %d", sc, sc);
    g_text(cx + 78, fy + 14, info, COL_TEXT, 1);
    g_text(cx + 78, fy + 32, note ? note : (glyph_present(sc) ? "" : "not in this font"),
           COL_TEXT_DIM, 1);

    /* the string being assembled, drawn in the face it will look like */
    g_round(cx + 78, fy + 46, cw - 78 - 14 - 152, 24, 6, COL_PANEL_3, 255);
    if (C.npick) {
        g_set_font(C.face);
        g_set_clip(cx + 82, fy + 46, cw - 78 - 22 - 152, 24);
        g_text(cx + 84, fy + 54 - (g_font_height(1) - 8) / 2, C.pick, COL_TEXT, 1);
        g_clear_clip();
        g_set_font(saved);
    } else {
        g_text(cx + 84, fy + 54, "pick characters above", COL_TEXT_DIM, 1);
    }

    int bx = cx + cw - 146;
    btn(bx, fy + 46, 44, 24, "Add", COL_PANEL_3, COL_TEXT);
    btn(bx + 48, fy + 46, 48, 24, "Copy", C.npick ? COL_ACCENT : COL_PANEL_3,
        C.npick ? 0xFFFFFF : COL_TEXT_DIM);
    btn(bx + 100, fy + 46, 32, 24, "Clr", COL_PANEL_3, COL_TEXT_DIM);

    g_set_font(saved);
}

/* --------------------------------------------------------------- input ---- */
static void cm_click(window_t *w, int lx, int ly) {
    (void)w;
    if (!C.cw) return;

    /* face buttons */
    if (ly >= 8 && ly < 32)
        for (int f = 0; f < 2; f++) {
            int bx = 52 + f * 96;
            if (lx >= bx && lx < bx + 90) { C.face = f; gui_request_redraw(); return; }
        }

    int fy = C.ch - FOOT_H;
    if (ly >= fy + 46 && ly < fy + 70) {
        int bx = C.cw - 146;
        if (lx >= bx && lx < bx + 44)             { pick_append(FIRST_CH + C.sel); gui_request_redraw(); return; }
        if (lx >= bx + 48 && lx < bx + 96)        { do_copy(); gui_request_redraw(); return; }
        if (lx >= bx + 100 && lx < bx + 132)      { C.npick = 0; C.pick[0] = 0; gui_request_redraw(); return; }
    }

    /* The grid. Clicks are client-local and the draw stored absolute
     * coordinates, so what matters is the centring margin, which is the same
     * arithmetic either way. */
    if (!C.cell) return;
    int margin_x = (C.cw - C.cell * COLS) / 2;
    if (lx < margin_x || ly < HEAD_H) return;
    int col = (lx - margin_x) / C.cell;
    int row = (ly - HEAD_H) / C.cell;
    if (col >= COLS) return;
    int i = row * COLS + col;
    if (i >= NCH) return;
    if (C.sel == i) pick_append(FIRST_CH + i);    /* second click adds it */
    C.sel = i;
    gui_request_redraw();
}

static void cm_key(window_t *w, char c) {
    (void)w;
    unsigned char u = (unsigned char)c;
    switch (u) {
    case KEY_LEFT:  if (C.sel > 0) C.sel--; break;
    case KEY_RIGHT: if (C.sel < NCH - 1) C.sel++; break;
    case KEY_UP:    if (C.sel >= COLS) C.sel -= COLS; break;
    case KEY_DOWN:  if (C.sel < NCH - COLS) C.sel += COLS; break;
    case KEY_HOME:  C.sel = 0; break;
    case KEY_END:   C.sel = NCH - 1; break;
    case KEY_COPY:  do_copy(); break;
    case '\n': case '\r': pick_append(FIRST_CH + C.sel); break;
    case '\b': if (C.npick) C.pick[--C.npick] = 0; break;
    default:
        /* Typing a character jumps to it -- the fastest way to find the
         * accented form of a letter is to press the letter. */
        if (u >= FIRST_CH && u <= LAST_CH) C.sel = u - FIRST_CH;
        else return;
    }
    gui_request_redraw();
}

void charmap_app_init(void) {
    memset(&C, 0, sizeof C);
    C.face = FONT_ARIAL;
    C.sel  = 0xB0 - FIRST_CH;               /* the degree sign: everyone's first errand */

    window_t *win = gui_add_window("Character Map", 420, 480, 0xFFB74D, ICON_CHARMAP);
    if (!win) return;
    win->draw  = cm_draw;
    win->click = cm_click;
    win->key   = cm_key;
    win->min_w = 320; win->min_h = 360;
    win->x = 420; win->y = 100;
}
